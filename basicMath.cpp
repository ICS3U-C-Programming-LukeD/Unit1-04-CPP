// Performs basic math operations

#include <cmath>
#include <iostream>
 int main() {
     std::cout << "5 + 5 = " << 5 + 5 << std::endl;
     std::cout << "6 - 2 = " << 6 - 2 << std::endl;
     std::cout << "3 x 6 = " << 3 * 6 << std::endl;
     std::cout << "14 / 12 = " << 14 / 12 << std::endl;
     std::cout << "4 ^ 3 = " << pow(4, 3) << std::endl;
     std::cout << "√16 = " << sqrt(16) << std::endl;
}
